# run_real_ticket_recovery_experiment.py
#
# 真实MemoryTicket恢复流程实验
# 测试5种ticket攻击场景：expired, replayed, tampered, rollback, wrong_session
#
# Task 3: Client-side code does NOT import TICKET_AUTH_KEY.
# Attack fixtures are generated server-side by generate_ticket_fixtures.py
# and read as opaque JSON input.

import csv
import json
import os
import socket
import tempfile
import time
from typing import Dict, Any, List, Tuple

from gmcp.config import (
    SERVER_TARGET_HOST,
    DEFAULT_PORT,
    CLIENT_ID,
    EPOCH,
    DATA_AUTH_KEY,
)
from gmcp.crypto_utils import hash_text, hmac_sha256_hex
from gmcp.memory import initial_memory, update_memory
from gmcp.packet import build_data_packet
from gmcp.recovery_protocol import (
    build_recovery_request as build_auth_recovery_request,
    verify_recovery_response,
)
from gmcp.experiment_stats import (
    ExperimentTracker,
    collect_experiment_metadata,
    calculate_statistics,
    format_statistics_for_csv,
)

OUTPUT_DIR = "results/real_ticket_recovery"
OUTPUT_CSV = os.path.join(OUTPUT_DIR, "real_ticket_recovery_results.csv")

# 实验参数
MESSAGE_COUNTS = [200, 500]  # 需要至少200条消息才能获得ticket
PAYLOAD_SIZES = [128]
ATTACK_TYPES = ["expired_ticket", "replayed_ticket", "tampered_ticket", "rollback_ticket", "wrong_session_ticket"]
REPEAT_COUNT = int(os.getenv("GMCP_REPEATS", "30"))
REPEATS = list(range(1, REPEAT_COUNT + 1))

SOCKET_TIMEOUT = 10.0

# Path to server-generated fixture file
FIXTURE_FILE = os.getenv(
    "GMCP_TICKET_FIXTURES",
    os.path.join(tempfile.gettempdir(), "gmcp_ticket_fixtures.json"),
)


def ensure_output_dir():
    os.makedirs(OUTPUT_DIR, exist_ok=True)


def load_fixtures() -> Dict[str, Any]:
    """Load ticket fixtures generated by generate_ticket_fixtures.py (server-side)."""
    if not os.path.exists(FIXTURE_FILE):
        raise FileNotFoundError(
            f"Fixture file not found: {FIXTURE_FILE}\n"
            "Run `python generate_ticket_fixtures.py` first to generate server-signed fixtures."
        )
    with open(FIXTURE_FILE, "r", encoding="utf-8") as f:
        return json.load(f)


def make_payload(seq: int, payload_size: int) -> str:
    prefix = "ticket-recovery-%d-" % seq
    remain = max(0, payload_size - len(prefix))
    return prefix + ("x" * remain)


def send_json_line(sock: socket.socket, packet: Dict[str, Any]):
    raw = json.dumps(packet, ensure_ascii=False).encode("utf-8") + b"\n"
    sock.sendall(raw)


def json_size(packet: Dict[str, Any]) -> int:
    return len(json.dumps(packet, ensure_ascii=False).encode("utf-8"))


def enable_tcp_nodelay(sock: socket.socket) -> None:
    try:
        sock.setsockopt(socket.IPPROTO_TCP, socket.TCP_NODELAY, 1)
    except Exception:
        pass


def recv_json_line(file_obj):
    line = file_obj.readline()
    if not line:
        raise ConnectionError("server closed connection")
    return json.loads(line)


def close_tcp(sock, file_obj):
    try:
        if file_obj:
            file_obj.close()
    except Exception:
        pass

    try:
        if sock:
            sock.shutdown(socket.SHUT_RDWR)
    except Exception:
        pass

    try:
        if sock:
            sock.close()
    except Exception:
        pass


def open_tcp():
    sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    enable_tcp_nodelay(sock)
    sock.settimeout(SOCKET_TIMEOUT)
    sock.connect((SERVER_TARGET_HOST, DEFAULT_PORT))
    file_obj = sock.makefile("r", encoding="utf-8", newline="\n")
    return sock, file_obj


def build_recovery_request(
    session_id: str,
    client_last_seq: int,
    client_last_mem: str,
    reason: str,
    ticket: Dict[str, Any] = {},
) -> Dict[str, Any]:

    request = {
        "type": "RECOVERY_REQUEST",
        "session_id": session_id,
        "client_id": CLIENT_ID,
        "epoch": EPOCH,
        "client_last_seq": client_last_seq,
        "client_last_mem": client_last_mem,
        "reason": reason,
        "timestamp": time.time(),
    }

    # 如果有ticket，添加到请求中
    if ticket:
        request["memory_ticket"] = ticket

    request["auth_tag"] = hmac_sha256_hex(DATA_AUTH_KEY, request)
    return request


def request_recovery_with_ticket(
    sock,
    file_obj,
    session_id: str,
    client_last_seq: int,
    client_last_mem: str,
    reason: str,
    ticket: Dict[str, Any] = {},
    recovery_nonce: str = "",
) -> Tuple[bool, Dict[str, Any], float, int, int, Dict[str, Any]]:

    start = time.time()

    request = build_auth_recovery_request(
        session_id=session_id,
        client_id=CLIENT_ID,
        epoch=EPOCH,
        client_last_seq=client_last_seq,
        client_last_mem=client_last_mem,
        reason=reason,
        extra={"memory_ticket": ticket} if ticket else None,
    )

    request_bytes = json_size(request)
    send_json_line(sock, request)
    response = recv_json_line(file_obj)
    response_bytes = json_size(response)

    latency_ms = (time.time() - start) * 1000

    # Verify the complete recovery response (client-side, no TICKET_AUTH_KEY needed)
    verified, verify_reason = verify_recovery_response(
        response, session_id, EPOCH, request["recovery_nonce"]
    )
    ok = verified and response.get("ok") is True

    # Client does NOT verify ticket HMAC – just records opaque info
    response_ticket = response.get("memory_ticket")
    ticket_info = {
        "ticket_nonce": response_ticket.get("ticket_nonce", "") if isinstance(response_ticket, dict) else "",
    }

    server_reject_reason = response.get("reason", "") if not ok else ""

    return ok, response, latency_ms, 2, request_bytes + response_bytes, ticket_info, server_reject_reason


def run_one_ticket_recovery_experiment(
    attack_type: str,
    message_count: int,
    payload_size: int,
    repeat_id: int,
    fixtures: Dict[str, Any],
) -> Dict[str, Any]:

    session_id = (
        f"ticket-recovery-{attack_type}-m{message_count}-p{payload_size}-"
        f"r{repeat_id}-{int(time.time() * 1000000)}"
    )

    initial_mem = initial_memory(session_id, CLIENT_ID, EPOCH, "demo-seed")
    current_mem = initial_mem

    final_server_mem = initial_mem
    final_server_last_seq = 0

    accepted_count = 0
    rejected_count = 0
    timeout_count = 0
    sent_count = 0

    attack_detected = False
    recovery_requested = False
    recovery_success = False
    memory_match_after_recovery = False

    recovery_latency_ms = 0.0
    recovery_extra_messages = 0
    recovery_extra_bytes = 0
    detection_reason = "normal"
    recovery_reason = "not_started"
    server_reject_reason = ""

    # ticket相关
    saved_ticket = None
    ticket_nonce = ""

    # 攻击点：在消息发送到一半时进行攻击
    attack_seq = min(150, max(2, message_count // 2))

    start_time = time.time()

    sock = None
    file_obj = None

    try:
        sock, file_obj = open_tcp()

        seq = 1
        while seq <= message_count:
            payload = make_payload(seq, payload_size)
            payload_hash = hash_text(payload)

            packet = build_data_packet(
                session_id=session_id,
                sender_id=CLIENT_ID,
                epoch=EPOCH,
                seq=seq,
                prev_mem=current_mem,
                payload=payload,
            )

            send_json_line(sock, packet)
            sent_count += 1

            try:
                response = recv_json_line(file_obj)
            except socket.timeout:
                timeout_count += 1
                detection_reason = "client timeout waiting for server response"
                break

            final_server_mem = response.get("last_mem", final_server_mem)
            final_server_last_seq = int(response.get("last_seq", final_server_last_seq))

            # 保存服务器签发的ticket
            if "memory_ticket" in response and response["memory_ticket"]:
                saved_ticket = response["memory_ticket"]
                print(f"[CLIENT] saved MemoryTicket at seq={final_server_last_seq}")

            if response.get("ok"):
                accepted_count += 1
                current_mem = final_server_mem
            else:
                rejected_count += 1

            # 在attack_seq处进行攻击
            if seq == attack_seq and not attack_detected:
                attack_detected = True
                detection_reason = f"{attack_type} attack at seq={attack_seq}"

                # 断开连接
                close_tcp(sock, file_obj)

                # Load attack fixture from server-generated file
                attack_ticket = fixtures.get(attack_type, {})

                # For replayed_ticket: first use the valid ticket successfully,
                # then replay the same ticket (should be rejected)
                if attack_type == "replayed_ticket" and saved_ticket:
                    sock, file_obj = open_tcp()
                    first_ok, first_resp, _, _, _, first_ticket_info, first_reject = request_recovery_with_ticket(
                        sock=sock,
                        file_obj=file_obj,
                        session_id=session_id,
                        client_last_seq=final_server_last_seq,
                        client_last_mem=current_mem,
                        reason="first_use",
                        ticket=saved_ticket,
                    )
                    if first_ok:
                        # First use succeeded, now replay
                        attack_ticket = saved_ticket
                    else:
                        attack_ticket = saved_ticket
                    # Close and reopen for the actual attack attempt
                    close_tcp(sock, file_obj)

                # 重新连接
                sock, file_obj = open_tcp()

                # 发起恢复请求
                recovery_requested = True
                (
                    ok,
                    recovery_response,
                    recovery_latency_ms,
                    recovery_extra_messages,
                    recovery_extra_bytes,
                    ticket_info,
                    server_reject_reason,
                ) = request_recovery_with_ticket(
                    sock=sock,
                    file_obj=file_obj,
                    session_id=session_id,
                    client_last_seq=final_server_last_seq,
                    client_last_mem=current_mem,
                    reason=detection_reason,
                    ticket=attack_ticket,
                )

                ticket_nonce = ticket_info.get("ticket_nonce", "")

                if ok:
                    recovery_success = True
                    recovery_reason = recovery_response.get("reason", "ok")
                    final_server_last_seq = int(recovery_response.get("server_last_seq", 0))
                    final_server_mem = recovery_response.get("server_last_mem", initial_mem)
                    current_mem = final_server_mem

                    # 检查恢复后记忆是否一致
                    memory_match_after_recovery = (current_mem == final_server_mem)

                    # 继续从恢复点发送消息
                    seq = final_server_last_seq + 1
                    continue
                else:
                    recovery_reason = server_reject_reason or recovery_response.get("reason", "recovery failed")
                    break

            seq += 1

    except Exception as e:
        detection_reason = f"experiment error: {e}"
        print(f"[ERROR] {e}")

    finally:
        close_tcp(sock, file_obj)

    elapsed = time.time() - start_time

    return {
        "session_id": session_id,
        "attack_type": attack_type,
        "message_count": message_count,
        "payload_size": payload_size,
        "repeat_id": repeat_id,
        "sent_count": sent_count,
        "accepted_count": accepted_count,
        "rejected_count": rejected_count,
        "timeout_count": timeout_count,
        "attack_detected": attack_detected,
        "detection_reason": detection_reason,
        "recovery_requested": recovery_requested,
        "recovery_success": recovery_success,
        "recovery_reason": recovery_reason,
        "server_reject_reason": server_reject_reason if not recovery_success else "",
        "memory_match_after_recovery": memory_match_after_recovery,
        "recovery_latency_ms": round(recovery_latency_ms, 2),
        "recovery_extra_messages": recovery_extra_messages,
        "recovery_extra_bytes": recovery_extra_bytes,
        "ticket_nonce": ticket_nonce,
        "elapsed_seconds": round(elapsed, 2),
        "final_server_last_seq": final_server_last_seq,
        "final_server_mem": final_server_mem,
    }


def run_all_experiments():
    ensure_output_dir()

    # Load server-generated fixtures
    try:
        fixtures = load_fixtures()
        print(f"[FIXTURES] Loaded {len(fixtures)} ticket fixtures from {FIXTURE_FILE}")
    except FileNotFoundError as e:
        print(f"[FIXTURES] {e}")
        print("[FIXTURES] Generating fixtures server-side...")
        from generate_ticket_fixtures import generate_fixtures, save_fixtures
        fixtures = generate_fixtures()
        save_fixtures(fixtures, FIXTURE_FILE)

    # 创建实验跟踪器
    tracker = ExperimentTracker("real_ticket_recovery")

    fieldnames = [
        "session_id", "attack_type", "message_count", "payload_size", "repeat_id",
        "sent_count", "accepted_count", "rejected_count", "timeout_count",
        "attack_detected", "detection_reason", "recovery_requested", "recovery_success",
        "recovery_reason", "server_reject_reason", "memory_match_after_recovery",
        "recovery_latency_ms", "recovery_extra_messages", "recovery_extra_bytes",
        "ticket_nonce", "elapsed_seconds", "final_server_last_seq", "final_server_mem",
    ]

    for message_count in MESSAGE_COUNTS:
        for payload_size in PAYLOAD_SIZES:
            for attack_type in ATTACK_TYPES:
                for repeat_id in REPEATS:
                    print(f"\n[EXPERIMENT] attack={attack_type}, msg={message_count}, "
                          f"payload={payload_size}, repeat={repeat_id}")

                    result = run_one_ticket_recovery_experiment(
                        attack_type=attack_type,
                        message_count=message_count,
                        payload_size=payload_size,
                        repeat_id=repeat_id,
                        fixtures=fixtures,
                    )

                    # 添加到跟踪器
                    tracker.add_result(result)

                    # 采样性能
                    tracker.sample_performance()

                    # 打印结果摘要
                    status = "✅ SUCCESS" if result["recovery_success"] else "❌ FAILED"
                    print(f"[RESULT] {status} - {result['recovery_reason']}")
                    print(f"  ticket_nonce: {result['ticket_nonce']}")

    # 保存结果到CSV
    tracker.save_results_to_csv(OUTPUT_CSV, fieldnames)
    print(f"\n[DONE] Experiment complete. {len(tracker.results)} results saved to {OUTPUT_CSV}")


if __name__ == "__main__":
    run_all_experiments()
